import { buildAbilityScores, emptySkillRanks } from "@/lib/calculations";
import type { Character } from "@/lib/types";
import { gameData } from "./game-data";

function withScores(character: Omit<Character, "abilityScores">): Character {
  const ancestry = gameData.ancestries.find((entry) => entry.id === character.ancestryId);
  if (!ancestry) throw new Error(`Missing ancestry ${character.ancestryId}`);
  return { ...character, abilityScores: buildAbilityScores(character, ancestry) };
}

